package mpack

// Archive layout (all paths are slash separated and relative):
//
//	manifest.json          metadata, always the first entry
//	bin/mise               the real mise executable (symlinks resolved)
//	config/config.toml     generated global config pinning exact versions
//	installs/<rel>/...     one subtree per packed tool, plus installs/.mise
const (
	ManifestName = "manifest.json"
	MiseBinName  = "bin/mise"
	// UnpackerName is an mpack binary for the archive's own platform, so the
	// receiving machine can unpack with nothing but tar to bootstrap.
	UnpackerName   = "bin/mpack"
	ConfigName     = "config/config.toml"
	InstallsPrefix = "installs"

	// ActivateName and InstalledManifestName are generated by unpack rather
	// than carried in the archive, but they are installed through the same
	// conflict checks and transaction as everything else.
	ActivateName          = "activate.sh"
	InstalledManifestName = "mpack-manifest.json"
	// DirenvName is sourced from a project's .envrc. It sets the same
	// environment as activate.sh but installs no shell hook, because direnv
	// evaluates it in its own process and manages entering and leaving.
	DirenvName = "direnv.envrc"
	// CatalogDir is mise's own record of where things are installed. The mise
	// docs describe installs/.mise as a catalog rather than a cache, so it is
	// preserved along with the install trees.
	CatalogDir = ".mise"

	// SchemaVersion is what a plain archive declares. An mpack that predates
	// a layout change must refuse such an archive rather than unpack it
	// partially, so anything that adds a new kind of content bumps this.
	SchemaVersion = 1
	// SchemaVersionUV is declared by archives that carry a Python
	// environment. An older mpack knows nothing of the uv/ directory and
	// would drop it while reporting success, leaving a tree that looks
	// unpacked but cannot restore; the higher number makes it stop instead.
	SchemaVersionUV = 2
	// SchemaVersionScoped records the tool selection for the project root and
	// each descendant mise scope. Older unpackers must reject this layout.
	SchemaVersionScoped = 3
)

// Manifest is the metadata stored at the head of every mpack archive.
type Manifest struct {
	Schema       int    `json:"schema"`
	MpackVersion string `json:"mpack_version"`
	CreatedAt    string `json:"created_at"`

	// OS and Arch are runtime.GOOS / runtime.GOARCH of the machine that
	// produced the archive. unpack refuses to run on a mismatch.
	OS   string `json:"os"`
	Arch string `json:"arch"`

	MiseVersion string `json:"mise_version"`

	// HomeRelativeProjectPath is the packed project directory expressed
	// relative to the packing user's home ("work/myapp"). It is what lets
	// unpack pick a default destination on a machine with a different user
	// name and a different home prefix (/Users vs /home). Absolute source
	// paths are deliberately not recorded: they are not needed and they leak
	// the packer's account name.
	HomeRelativeProjectPath string `json:"home_relative_project_path,omitempty"`

	Tools []Tool `json:"tools"`
	// Scopes select from Tools at each project-relative directory. Tools is
	// the physical union to install; Scopes records which version is active
	// in each directory. A root scope with Path "." is required for schema 3.
	Scopes     []Scope `json:"scopes,omitempty"`
	HasCatalog bool    `json:"has_catalog"`
	// HasUnpacker records whether bin/mpack is present, so unpack installs it
	// alongside everything else.
	HasUnpacker bool `json:"has_unpacker,omitempty"`

	// EnvVarNames lists the names of environment variables that the source
	// mise configuration would set. Values are deliberately never recorded:
	// mise config env can hold secrets.
	EnvVarNames []string `json:"env_var_names"`

	// RewrittenLinks are symlinks whose stored target was absolute and inside
	// the source installs root; they are rewritten on unpack.
	RewrittenLinks []LinkNote `json:"rewritten_links,omitempty"`
	// DanglingLinks point inside the packed set but at something that does not
	// currently exist. Kept as is, reported as a warning.
	DanglingLinks []LinkNote `json:"dangling_links,omitempty"`
	// UnresolvedLinks point outside the packed set. Packing fails on these
	// unless --allow-unresolved was given, in which case they are recorded
	// here so the breakage is never silent.
	UnresolvedLinks []LinkNote `json:"unresolved_links,omitempty"`

	// UVProject is present when the archive carries a Python environment to
	// rebuild, rather than only mise tools.
	UVProject *UVProject `json:"uv_project,omitempty"`

	Stats Stats `json:"stats"`
}

// Scope records the complete active tool selection at one project-relative
// directory. Descendants without their own scope inherit the deepest scope
// on their path.
type Scope struct {
	Path  string `json:"path"`
	Tools []Tool `json:"tools"`
}

// MpackSubdir is the directory, relative to the project directory, where an
// unpacked toolchain lives by default. Keeping it inside the project mirrors
// mise's directory-scoped model while staying clear of the project's own
// files.
const MpackSubdir = ".mpack"

// Tool is one packed mise tool at one exact version.
type Tool struct {
	// Name is the mise tool name, including the backend prefix ("cargo:pwkit").
	Name string `json:"name"`
	// Version is the resolved exact version.
	Version string `json:"version"`
	// RequestedVersion is what the source config asked for ("latest", ...).
	RequestedVersion string `json:"requested_version"`
	// RelPath is the tool's directory relative to the installs root. It is not
	// derivable from Name: "cargo:pwkit" installs under "cargo-pwkit/0.1.0".
	RelPath string `json:"rel_path"`
	// ConfigSource is the config file that activated the tool on the source
	// machine, recorded for traceability as a home-relative path ("~/..."),
	// or omitted when it lay outside the home directory. Absolute source
	// paths are never stored: they would carry the packer's account name.
	ConfigSource string `json:"config_source,omitempty"`
}

// LinkNote records one noteworthy symlink.
type LinkNote struct {
	// Path is the link location relative to the installs root.
	Path string `json:"path"`
	// Target is the original link target, with the packer's home directory
	// replaced by "~". A target outside the home directory is recorded as an
	// empty string rather than leaking an absolute source path; Reason still
	// explains what was wrong with it.
	Target string `json:"target"`
	// Reason explains why the link needed attention.
	Reason string `json:"reason,omitempty"`
}

// Stats is a summary of the packed payload.
type Stats struct {
	Files    int   `json:"files"`
	Dirs     int   `json:"dirs"`
	Symlinks int   `json:"symlinks"`
	Bytes    int64 `json:"bytes"`
}
